export const MAP = { lon0: -180, lat0: 84, cell: 2.5, cols: 144, rows: 57, px: 3 };

let mask: Uint8Array | null = null;

function isLand(lon: number, lat: number): boolean {
  if (LAKES.some(p => inPoly(lon, lat, p))) return false;
  return LAND.some(p => inPoly(lon, lat, p));
}

function buildMask(): Uint8Array {
  const m = new Uint8Array(MAP.cols * MAP.rows);
  for (let y = 0; y < MAP.rows; y++) for (let x = 0; x < MAP.cols; x++) {
    let hits = 0;
    for (const [sx, sy] of [[0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75], [0.5, 0.5]]) {
      if (isLand(MAP.lon0 + (x + sx) * MAP.cell, MAP.lat0 - (y + sy) * MAP.cell)) hits++;
    }
    m[y * MAP.cols + x] = hits >= 2 ? 1 : 0;
  }
  return m;
}

export function toCell(lon: number, lat: number): [number, number] {
  if (lon > 900) return [MAP.cols - 7, 5];
  return [(lon - MAP.lon0) / MAP.cell, (MAP.lat0 - lat) / MAP.cell];
}

const inBox = (lon: number, lat: number, b: [number, number, number, number]) => lon >= b[0] && lon <= b[1] && lat >= b[2] && lat <= b[3];
const USA: [number, number, number, number] = [-125, -66.5, 24.5, 49];
const ALASKA: [number, number, number, number] = [-170, -141, 54, 72];
const CANADA: [number, number, number, number] = [-141, -52, 49.01, 84];
const GREENLAND: [number, number, number, number] = [-74, -12, 59, 84];

/** Draws the map. `done` lists completed operation ids; `hot` is the hovered operation. */
export function drawWorld(canvas: HTMLCanvasElement, done: Set<string>, hot: string | null, t: number): void {
  mask ??= buildMask();
  const P = MAP.px;
  const W = MAP.cols * P, H = MAP.rows * P;
  if (canvas.width !== W) { canvas.width = W; canvas.height = H; }
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  // Ocean with a dithered swell and graticule.
  ctx.fillStyle = '#0b1d40';
  ctx.fillRect(0, 0, W, H);
  ctx.fillStyle = '#0f2552';
  for (let y = 0; y < MAP.rows; y++) for (let x = 0; x < MAP.cols; x++) {
    if ((x + y * 3 + Math.floor(t * 2)) % 9 === 0) ctx.fillRect(x * P, y * P + 1, P, 1);
  }
  ctx.fillStyle = 'rgba(120, 160, 220, 0.12)';
  for (let lat = 60; lat >= -60; lat -= 30) ctx.fillRect(0, Math.round(((MAP.lat0 - lat) / MAP.cell) * P), W, 1);
  for (let lon = -150; lon <= 180; lon += 30) ctx.fillRect(Math.round(((lon - MAP.lon0) / MAP.cell) * P), 0, 1, H);
  const at = (x: number, y: number) => (x < 0 || y < 0 || x >= MAP.cols || y >= MAP.rows ? 0 : mask![y * MAP.cols + x]);
  const canada51 = done.has('canada'), greenland = done.has('greenland');
  for (let y = 0; y < MAP.rows; y++) for (let x = 0; x < MAP.cols; x++) {
    if (!at(x, y)) continue;
    const lon = MAP.lon0 + (x + 0.5) * MAP.cell, lat = MAP.lat0 - (y + 0.5) * MAP.cell;
    const american = inBox(lon, lat, USA) || inBox(lon, lat, ALASKA) || (canada51 && inBox(lon, lat, CANADA)) || (greenland && inBox(lon, lat, GREENLAND));
    let c: string;
    if (american) {
      // Stars and stripes: a blue canton in the north-west of the lower 48, stripes elsewhere.
      const canton = inBox(lon, lat, [-125, -101, 38, 49]);
      if (canton) c = (x + y) % 2 === 0 && y % 2 === 0 ? '#ffffff' : '#1f2f6e';
      else c = y % 2 === 0 ? '#c8283a' : '#f2f2f2';
    } else if (Math.abs(lat) > 62) c = '#b9c6cf';
    else if ((lat > 15 && lat < 32 && lon > -15 && lon < 60) || (lat < -20 && lat > -32 && lon > 118 && lon < 145)) c = '#b79a5e';
    else c = (x * 7 + y * 13) % 11 === 0 ? '#5a7535' : '#6a8a3e';
    ctx.fillStyle = c;
    ctx.fillRect(x * P, y * P, P, P);
    // Coast: light on the upper-left, dark on the lower-right.
    if (!at(x, y - 1) || !at(x - 1, y)) { ctx.fillStyle = 'rgba(255,255,255,0.22)'; ctx.fillRect(x * P, y * P, P, 1); }
    if (!at(x, y + 1) || !at(x + 1, y)) { ctx.fillStyle = 'rgba(0,0,0,0.35)'; ctx.fillRect(x * P, y * P + P - 1, P, 1); }
  }
  // Mars, off the edge of the world.
  const [mx, my] = toCell(999, 999);
  ctx.fillStyle = '#c45a2c';
  ctx.beginPath(); ctx.arc(mx * P, my * P, 9, 0, Math.PI * 2); ctx.fill();
  ctx.fillStyle = '#8e3a1a';
  ctx.fillRect(mx * P - 4, my * P - 2, 4, 3); ctx.fillRect(mx * P + 2, my * P + 3, 3, 2);
  // Labels for completed operations.
  ctx.font = '8px Silkscreen, monospace';
  ctx.textAlign = 'center';
  for (const g of GEO) {
    if (!g.label || !done.has(g.id)) continue;
    const [cx, cy] = toCell(g.lon, g.lat);
    const ly = Math.max(9, g.id === 'gulf' ? cy * P + 10 : cy * P - 10);
    ctx.fillStyle = '#000';
    ctx.fillText(g.label, cx * P + 1, ly + 1);
    ctx.fillStyle = g.id === 'dome' ? '#f5d33f' : '#ffffff';
    ctx.fillText(g.label, cx * P, ly);
  }
  // Pins: a flag for completed operations, a pulsing target ring otherwise.
  const flag = raster('flagpin');
  for (const g of GEO) {
    const [cx, cy] = toCell(g.lon, g.lat);
    const px = Math.round(cx * P), py = Math.round(cy * P);
    if (done.has(g.id)) {
      ctx.drawImage(flag.canvas, px - 1, py - flag.h + 1);
    } else {
      const pulse = (t * 1.6 + g.lon / 50) % 1;
      ctx.strokeStyle = g.id === hot ? '#f5d33f' : `rgba(255, 70, 70, ${1 - pulse})`;
      ctx.lineWidth = 1;
      ctx.beginPath(); ctx.arc(px + 0.5, py + 0.5, 2 + pulse * 6, 0, Math.PI * 2); ctx.stroke();
      ctx.fillStyle = g.id === hot ? '#f5d33f' : '#ff4646';
      ctx.fillRect(px - 1, py - 1, 3, 3);
    }
    if (g.id === hot) {
      ctx.strokeStyle = '#f5d33f';
      ctx.strokeRect(px - 8.5, py - 8.5, 17, 17);
    }
  }
}

/** Returns the operation nearest to a point on the canvas, if any is within reach. */
export function geoAt(canvas: HTMLCanvasElement, clientX: number, clientY: number, list: GeoOp[]): GeoOp | null {
  const r = canvas.getBoundingClientRect();
  const x = ((clientX - r.left) / r.width) * MAP.cols, y = ((clientY - r.top) / r.height) * MAP.rows;
  let best: GeoOp | null = null, bd = 16;
  for (const g of list) {
    const [cx, cy] = toCell(g.lon, g.lat);
    const d = (cx - x) ** 2 + (cy - y) ** 2;
    if (d < bd) { bd = d; best = g; }
  }
  return best;
}
